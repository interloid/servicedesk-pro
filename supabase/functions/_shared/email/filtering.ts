// Which emails become tickets at all.
//
// A connected Gmail inbox is often a person's own. The watch covers the
// whole inbox; only mail addressed to the configured receiving address is
// filed, and automated mail (bounces, auto-replies, our own notifications) is
// dropped before it can loop.

import {
  addressBase,
  canonicalAddress,
  isValidEmail,
  sameAddress,
} from "./address.ts";
import type { EmailIntegration, IncomingEmail } from "./types.ts";

export type IgnoreReason =
  | "not_support_address"
  | "auto_generated"
  | "system_sender"
  | "sender_is_mailbox"
  | "invalid_sender"
  | "spam_or_trash"
  | "draft_or_sent"
  | "message_unavailable";

/** Local parts of addresses that never belong to a person. */
const SYSTEM_LOCAL_PART =
  /^(no-?reply|do-?not-?reply|noreply-[^@]*|mailer-daemon|postmaster|bounces?|bounce-[^@]*|notifications?-noreply)(\+[^@]*)?$/i;

type SupportAddressIntegration = Pick<
  EmailIntegration,
  "receivingEmail" | "connectedEmail"
>;

/**
 * True when the email was sent to the integration's receiving address: in
 * To, in Cc, or as an envelope recipient (Delivered-To / X-Original-To, which
 * is how a Bcc or a forwarding rule shows up). Case-insensitive; Gmail's dots
 * and googlemail.com are folded, the +tag must match (see canonicalAddress).
 */
export function isSupportEmail(
  email: Pick<IncomingEmail, "to" | "cc" | "deliveredTo">,
  integration: SupportAddressIntegration,
): boolean {
  const target = canonicalAddress(integration.receivingEmail);

  return [...email.to, ...email.cc, ...email.deliveredTo].some(
    (recipient) => canonicalAddress(recipient) === target,
  );
}

/** The recipient that matched, for the event record. */
export function matchedSupportAddress(
  email: Pick<IncomingEmail, "to" | "cc" | "deliveredTo">,
  integration: SupportAddressIntegration,
): string | null {
  const target = canonicalAddress(integration.receivingEmail);

  return (
    [...email.to, ...email.cc, ...email.deliveredTo].find(
      (recipient) => canonicalAddress(recipient) === target,
    ) ?? null
  );
}

export function isSystemAddress(address: string): boolean {
  const at = address.lastIndexOf("@");
  return at > 0 && SYSTEM_LOCAL_PART.test(address.slice(0, at));
}

/**
 * Who the email is from, as far as the ticket goes. Normally From. A Google
 * Group or forwarding service that rewrites From to the support address
 * itself (DMARC "via" rewriting) puts the customer in Reply-To, so that is
 * used instead -- only in that case, since Reply-To is otherwise free text
 * the sender chose.
 */
export function effectiveSender(
  email: Pick<IncomingEmail, "from" | "replyTo">,
  integration: SupportAddressIntegration,
): { email: string; name?: string } {
  const fromIsMailbox =
    sameAddress(email.from.email, integration.receivingEmail) ||
    addressBase(email.from.email) === addressBase(integration.connectedEmail);

  if (fromIsMailbox && email.replyTo && isValidEmail(email.replyTo.email)) {
    return email.replyTo;
  }

  return email.from;
}

export interface ScreenOptions {
  /** Addresses the platform sends from (FROM_EMAIL): never customers. */
  systemSenders?: string[];
}

/**
 * The first reason to file nothing, or null when the email should go on to
 * threading and ticket creation. Order matters only for what the admin sees.
 */
export function screenEmail(
  email: IncomingEmail,
  integration: SupportAddressIntegration,
  options: ScreenOptions = {},
): IgnoreReason | null {
  if (email.labels.includes("SPAM") || email.labels.includes("TRASH")) {
    return "spam_or_trash";
  }

  if (email.labels.includes("DRAFT") || email.labels.includes("SENT")) {
    return "draft_or_sent";
  }

  if (!isSupportEmail(email, integration)) {
    return "not_support_address";
  }

  const sender = effectiveSender(email, integration);

  if (!isValidEmail(sender.email)) {
    return "invalid_sender";
  }

  if (
    addressBase(sender.email) === addressBase(integration.connectedEmail) ||
    sameAddress(sender.email, integration.receivingEmail)
  ) {
    return "sender_is_mailbox";
  }

  if (
    isSystemAddress(sender.email) ||
    (options.systemSenders ?? []).some((address) =>
      sameAddress(address, sender.email),
    )
  ) {
    return "system_sender";
  }

  if (email.autoGenerated) {
    return "auto_generated";
  }

  return null;
}
