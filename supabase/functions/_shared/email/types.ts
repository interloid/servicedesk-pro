// Provider-neutral types for email-to-ticket.
//
// Everything under _shared/email/ is plain TypeScript with no Deno or Node
// APIs (only fetch, WebCrypto, TextEncoder/TextDecoder, atob/btoa), so the
// same files run in the Edge Functions, in the Next.js OAuth routes, and in
// Vitest. Nothing here knows about Gmail: provider code lives in
// providers/<name>/ and hands back these shapes.

export type EmailProviderName = "gmail";

export interface EmailAddress {
  email: string;
  name?: string;
}

export interface IncomingAttachment {
  filename: string;
  /** As the sender declared it. Never trusted for storage. */
  mimeType: string;
  /** Bytes, as the provider reports them. */
  size: number;
  /** Fetch the content with EmailProvider.getAttachmentContent. */
  providerAttachmentId?: string;
  /** Content the provider already returned with the message. */
  data?: Uint8Array;
  contentId?: string;
  /** Content-Disposition inline, or referenced from the HTML (a signature logo). */
  inline: boolean;
}

export interface IncomingEmail {
  provider: EmailProviderName;

  providerMessageId: string;

  providerThreadId?: string;

  /** RFC 5322 Message-ID, angle brackets included. */
  messageId?: string;

  inReplyTo?: string;

  references?: string;

  from: EmailAddress;

  /** Reply-To, when the sender set one. */
  replyTo?: EmailAddress;

  to: string[];

  cc: string[];

  /** Delivered-To / X-Original-To: the envelope recipients, BCC included. */
  deliveredTo: string[];

  subject: string;

  textBody?: string;

  htmlBody?: string;

  receivedAt: Date;

  attachments: IncomingAttachment[];

  /** Auto-Submitted, Precedence: bulk/junk/auto_reply, X-Autoreply... */
  autoGenerated: boolean;

  /** Provider folders/labels, normalised to upper case (INBOX, SPAM...). */
  labels: string[];
}

export type IntegrationStatus =
  "connecting" | "connected" | "expired" | "error" | "disconnected";

/** A connected mailbox, as the worker loads it (service role only). */
export interface EmailIntegration {
  id: string;
  tenantId: string;
  provider: EmailProviderName;
  connectedEmail: string;
  receivingEmail: string;
  enabled: boolean;
  autoCreateCustomer: boolean;
  status: IntegrationStatus;
  accessTokenEncrypted: string | null;
  refreshTokenEncrypted: string | null;
  tokenExpiresAt: Date | null;
  providerHistoryId: string | null;
  watchExpiration: Date | null;
}

export interface TokenResult {
  accessToken: string;
  expiresAt: Date;
  /** Only when the provider issued a new one (first exchange, rotation). */
  refreshToken?: string;
  scope?: string;
}

export interface MailboxChanges {
  /** New messages since the cursor, oldest first, without duplicates. */
  messageIds: string[];
  /** The cursor to save once the ids are recorded. */
  historyId: string;
  /**
   * The saved cursor was too old for the provider's history; messageIds is a
   * best-effort list of recent inbox mail instead.
   */
  cursorReset: boolean;
}

export interface WatchResult {
  historyId: string;
  expiration: Date;
}

/**
 * What the shared pipeline needs from a provider. GmailProvider is the only
 * implementation today; Outlook would add another without touching the
 * processor, the queue or the ticket logic.
 */
export interface EmailProvider {
  readonly name: EmailProviderName;

  /** Message ids added to the inbox after `historyId`, and the next cursor. */
  listChanges(
    integration: EmailIntegration,
    historyId: string,
  ): Promise<MailboxChanges>;

  /** listChanges, then every message in full. */
  getNewMessages(
    integration: EmailIntegration,
    historyId: string,
  ): Promise<IncomingEmail[]>;

  getMessage(
    integration: EmailIntegration,
    messageId: string,
  ): Promise<IncomingEmail>;

  getAttachmentContent(
    integration: EmailIntegration,
    messageId: string,
    attachment: IncomingAttachment,
  ): Promise<Uint8Array>;

  refreshAccessToken(integration: EmailIntegration): Promise<TokenResult>;

  /** Register (or renew) push notifications for the inbox. */
  watch(integration: EmailIntegration): Promise<WatchResult>;

  /** The mailbox's current cursor, for a mailbox that has none yet. */
  getCurrentHistoryId(integration: EmailIntegration): Promise<string>;
}

/** The queue payload: email_sync_jobs, kind = 'sync'. */
export interface GmailSyncJob {
  tenantId: string;
  integrationId: string;
  historyId: string;
}
