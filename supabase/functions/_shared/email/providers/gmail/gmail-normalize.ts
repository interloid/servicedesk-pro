// Gmail API message (format=full) -> IncomingEmail.
//
// Gmail has already undone each part's Content-Transfer-Encoding: body.data
// is the part's raw bytes in base64url, still in the part's charset. Large
// parts (and every attachment) come with an attachmentId instead of data.

import {
  normalizeEmail,
  parseAddress,
  parseAddressList,
} from "../../address.ts";
import type { IncomingAttachment, IncomingEmail } from "../../types.ts";
import type {
  GmailHeader,
  GmailMessage,
  GmailMessagePart,
} from "./gmail-api.ts";
import {
  base64UrlToBytes,
  decodeBytes,
  decodeEncodedWords,
  parseHeaderParams,
} from "./mime.ts";

/** Header lookups are case-insensitive; a repeated header keeps every value. */
function headerMap(headers: GmailHeader[] | undefined): Map<string, string[]> {
  const map = new Map<string, string[]>();

  for (const header of headers ?? []) {
    const key = header.name.toLowerCase();
    const list = map.get(key) ?? [];
    list.push(header.value ?? "");
    map.set(key, list);
  }

  return map;
}

function first(map: Map<string, string[]>, name: string): string | undefined {
  return map.get(name)?.[0];
}

/** Precedence values that mean a machine sent it. "list" is NOT one: a Google Group forwarding a customer sets it. */
const AUTOMATED_PRECEDENCE = new Set(["bulk", "junk", "auto_reply"]);

export function isAutoGenerated(headers: Map<string, string[]>): boolean {
  // Sent by this platform (supabase/functions/_shared/gmail.ts): never filed.
  if (headers.has("x-servicedesk-origin")) return true;

  const autoSubmitted = first(headers, "auto-submitted")?.trim().toLowerCase();

  if (autoSubmitted && autoSubmitted !== "no") return true;

  const precedence = first(headers, "precedence")?.trim().toLowerCase();
  if (precedence && AUTOMATED_PRECEDENCE.has(precedence)) return true;

  if (headers.has("x-autoreply") || headers.has("x-autorespond")) return true;

  const suppress =
    first(headers, "x-auto-response-suppress")?.toLowerCase() ?? "";
  // Exchange marks its own out-of-office and delivery reports this way.
  if (
    /\b(oof|dr|autoreply)\b/.test(suppress) &&
    headers.has("x-ms-exchange-generated-message-source")
  ) {
    return true;
  }

  const returnPath = first(headers, "return-path")?.trim();
  // A null envelope sender is a bounce (RFC 5321 4.5.5).
  if (returnPath === "<>") return true;

  return false;
}

interface Collected {
  text: string[];
  html: string[];
  attachments: IncomingAttachment[];
}

function partCharset(
  headers: Map<string, string[]>,
  part: GmailMessagePart,
): string | undefined {
  const contentType = first(headers, "content-type") ?? part.mimeType ?? "";
  return parseHeaderParams(contentType).params.charset;
}

function partFilename(
  headers: Map<string, string[]>,
  part: GmailMessagePart,
): string {
  if (part.filename) return decodeEncodedWords(part.filename);

  const disposition = parseHeaderParams(first(headers, "content-disposition"));
  if (disposition.params.filename)
    return decodeEncodedWords(disposition.params.filename);

  const type = parseHeaderParams(first(headers, "content-type"));
  return type.params.name ? decodeEncodedWords(type.params.name) : "";
}

function walk(part: GmailMessagePart, out: Collected, depth: number): void {
  if (depth > 20) return;

  const headers = headerMap(part.headers);
  const mimeType = (part.mimeType ?? "application/octet-stream").toLowerCase();
  const disposition = parseHeaderParams(
    first(headers, "content-disposition"),
  ).value;
  const filename = partFilename(headers, part);
  const contentId = first(headers, "content-id")?.trim();

  if (mimeType.startsWith("multipart/") && part.parts?.length) {
    // multipart/alternative: the parts are the same content; collect both a
    // text and an html version, one of each, from the richest end.
    if (mimeType === "multipart/alternative") {
      const nested: Collected = { text: [], html: [], attachments: [] };
      for (const child of part.parts) walk(child, nested, depth + 1);
      if (nested.text.length)
        out.text.push(nested.text[nested.text.length - 1]);
      if (nested.html.length)
        out.html.push(nested.html[nested.html.length - 1]);
      out.attachments.push(...nested.attachments);
      return;
    }

    for (const child of part.parts) walk(child, out, depth + 1);
    return;
  }

  const isAttachment =
    disposition === "attachment" ||
    Boolean(filename) ||
    Boolean(part.body?.attachmentId && !mimeType.startsWith("text/"));

  if (isAttachment) {
    const data = part.body?.data ? base64UrlToBytes(part.body.data) : undefined;
    out.attachments.push({
      filename:
        filename ||
        (mimeType === "message/rfc822"
          ? "forwarded-message.eml"
          : "attachment"),
      mimeType,
      size: part.body?.size ?? data?.length ?? 0,
      providerAttachmentId: part.body?.attachmentId,
      data,
      contentId: contentId || undefined,
      inline: disposition === "inline" || (!disposition && Boolean(contentId)),
    });
    return;
  }

  if (!part.body?.data) return;

  const text = decodeBytes(
    base64UrlToBytes(part.body.data),
    partCharset(headers, part),
  );

  if (mimeType === "text/html") out.html.push(text);
  else if (mimeType.startsWith("text/") && mimeType !== "text/calendar")
    out.text.push(text);
}

function addressList(headers: Map<string, string[]>, name: string): string[] {
  return (headers.get(name) ?? []).flatMap((value) =>
    parseAddressList(decodeEncodedWords(value)).map((a) => a.email),
  );
}

export function normalizeGmailMessage(message: GmailMessage): IncomingEmail {
  const payload = message.payload ?? {};
  const headers = headerMap(payload.headers);
  const collected: Collected = { text: [], html: [], attachments: [] };

  walk(payload, collected, 0);

  const fromHeader = decodeEncodedWords(first(headers, "from") ?? "");
  const from = parseAddress(fromHeader) ??
    parseAddressList(fromHeader)[0] ?? { email: "" };
  const replyToHeader = first(headers, "reply-to");
  const replyTo = replyToHeader
    ? parseAddressList(decodeEncodedWords(replyToHeader))[0]
    : undefined;

  const deliveredTo = [
    ...(headers.get("delivered-to") ?? []),
    ...(headers.get("x-original-to") ?? []),
  ]
    .map((value) => normalizeEmail(value))
    .filter(Boolean);

  const internalDate = Number(message.internalDate);
  const dateHeader = Date.parse(first(headers, "date") ?? "");

  return {
    provider: "gmail",
    providerMessageId: message.id,
    providerThreadId: message.threadId,
    messageId: first(headers, "message-id")?.trim() || undefined,
    inReplyTo: first(headers, "in-reply-to")?.trim() || undefined,
    references: (headers.get("references") ?? []).join(" ").trim() || undefined,
    from: { email: from.email, name: from.name },
    replyTo,
    to: addressList(headers, "to"),
    cc: addressList(headers, "cc"),
    deliveredTo: Array.from(new Set(deliveredTo)),
    subject: decodeEncodedWords(first(headers, "subject") ?? "").trim(),
    textBody: collected.text.length ? collected.text.join("\n\n") : undefined,
    htmlBody: collected.html.length ? collected.html.join("\n") : undefined,
    receivedAt:
      Number.isFinite(internalDate) && internalDate > 0
        ? new Date(internalDate)
        : Number.isFinite(dateHeader)
          ? new Date(dateHeader)
          : new Date(),
    attachments: collected.attachments,
    autoGenerated: isAutoGenerated(headers),
    labels: (message.labelIds ?? []).map((label) => label.toUpperCase()),
  };
}
